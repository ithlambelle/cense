import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { z } from "zod";

import { EVENTS, TRACKING_PLAN_VERSION } from "../src/lib/analytics-catalog";
import { baseProperties } from "../src/lib/analytics-config";

// Writes docs/analytics-events.md from the event catalog, so the readable
// tracking plan can never drift from what the code sends. CI fails when the
// file is out of date (npm run analytics:docs:check).

type JsonSchema = { type?: string | string[]; enum?: unknown[]; format?: string; anyOf?: JsonSchema[]; minimum?: number; maximum?: number; pattern?: string };

function describe(schema: JsonSchema): string {
  if (schema.anyOf) return schema.anyOf.map(describe).join(" or ");
  if (schema.enum) return schema.enum.map((value) => `\`${String(value)}\``).join(", ");
  if (schema.format === "uuid") return "uuid";
  if (schema.pattern) return "catalog id";
  if (schema.type === "integer" && schema.minimum !== undefined) return `integer ${schema.minimum} to ${schema.maximum}`;
  return Array.isArray(schema.type) ? schema.type.join(" or ") : (schema.type ?? "any");
}

const rows = Object.entries(EVENTS).map(([name, entry]) => {
  const json = z.toJSONSchema(entry.properties) as { properties?: Record<string, JsonSchema> };
  const props = Object.entries(json.properties ?? {})
    .map(([prop, schema]) => `\`${prop}\`: ${describe(schema)}`)
    .join("<br>");
  const ledger = "ledger" in entry ? entry.ledger : "PostHog only";
  const from = "sentFrom" in entry ? entry.sentFrom : "browser";
  return `| \`${name}\` | ${entry.question} | ${props || "none"} | ${from} | ${ledger} | ${entry.owner} | ${entry.addedIn} |`;
});

const common = Object.keys(baseProperties()).map((name) => `\`${name}\``).join(", ");

const doc = `<!-- Generated by npm run analytics:docs from web/src/lib/analytics-catalog.ts. Do not edit by hand. -->

# Analytics events

Tracking plan version ${TRACKING_PLAN_VERSION}. Every event Cense sends to PostHog, the question it answers and the only properties it may carry. \`track()\` in \`web/src/lib/analytics.ts\` (the browser) and \`captureServer()\` in \`web/src/lib/analytics-server.ts\` (the server, for moments with no browser open) reject anything not listed here, and a lint rule stops code from calling PostHog any other way.

Sent with every event: ${common}. PostHog adds its own (\`$current_url\` and the like), with everything after "?" or "#" removed before sending. Events marked with a ledger copy a Postgres row; the falsifiers and the D24 numbers are counted from Postgres, and PostHog is checked against it.

| Event | Question it answers | Properties | Sent from | Ledger | Owner | Added in plan |
|---|---|---|---|---|---|---|
${rows.join("\n")}
`;

writeFileSync(resolve(import.meta.dirname, "../../docs/analytics-events.md"), doc);
